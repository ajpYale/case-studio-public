"""Tokenomics from the measured run log (docs/run_log.json): per-level averages, monthly and scale costs.

Prints a JSON summary used to write report section 4. Prices are the course's (generator.PRICES).
"""

from __future__ import annotations

import json
import statistics as st
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent
sys.path.insert(0, str(DOCS.parent / "backend"))
import generator  # noqa: E402

LEVELS = ["easy", "medium", "hard", "instant_offer"]
# Assumed usage (stated in the report): an active candidate in recruiting season generates 8 cases a
# month (practises ~16, half generated by their partner), in this difficulty mix.
CASES_PER_USER_MONTH = 8
MIX = {"easy": 0.15, "medium": 0.35, "hard": 0.35, "instant_offer": 0.15}
STRONG = {"easy": "gpt-5.6-terra", "medium": "gpt-5.6-terra", "hard": "gpt-5.6-terra", "instant_offer": "gpt-5.6-sol"}


def main() -> None:
    runs = [r for r in json.loads((DOCS / "run_log.json").read_text(encoding="utf-8")) if r.get("usd") is not None]
    out: dict = {"levels": {}}
    for lv in LEVELS:
        rs = [r for r in runs if r["difficulty"] == lv]
        if not rs:
            continue
        def avg(k):
            return st.mean(r[k] for r in rs)
        strong_est = st.mean(generator.cost_usd(STRONG[lv], r["input"], r["cached"], r["output"]) for r in rs)
        out["levels"][lv] = {
            "n": len(rs), "calls": avg("calls"), "input": avg("input"), "cached": avg("cached"), "output": avg("output"),
            "cached_share": sum(r["cached"] for r in rs) / sum(r["input"] for r in rs),
            "usd": avg("usd"), "usd_min": min(r["usd"] for r in rs), "usd_max": max(r["usd"] for r in rs),
            "minutes": avg("minutes"), "verified": sum(r["quality"] == "verified" for r in rs),
            "strong_est_usd": strong_est,
        }
    lv = out["levels"]
    per_case = sum(MIX[k] * lv[k]["usd"] for k in MIX if k in lv)
    per_case_strong = sum(MIX[k] * lv[k]["strong_est_usd"] for k in MIX if k in lv)
    per_user = per_case * CASES_PER_USER_MONTH
    per_user_strong = per_case_strong * CASES_PER_USER_MONTH
    out["blend"] = {"per_case": per_case, "per_user_month": per_user, "users_100": per_user * 100,
                    "users_10000": per_user * 10_000, "per_case_strong_est": per_case_strong,
                    "per_user_month_strong_est": per_user_strong, "users_100_strong": per_user_strong * 100,
                    "users_10000_strong": per_user_strong * 10_000}
    # Without caching: price every cached token as normal input.
    nocache = [generator.cost_usd("gpt-6-luna", r["input"], 0, r["output"]) for r in runs]
    withcache = [r["usd"] for r in runs]
    out["caching_saving_share"] = 1 - sum(withcache) / sum(nocache)
    out["output_share_of_cost"] = sum(r["output"] * 0.5 / 1e6 for r in runs) / sum(withcache)
    out["total_luna_usd"] = sum(withcache)
    out["n_runs_measured"] = len(runs)
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
